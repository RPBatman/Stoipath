# ----------------------------------------------------------------------------------------------- small helpers
def ts(s):
    if not s:
        return None
    try:
        return dt.datetime.fromisoformat(s.replace('Z', '+00:00'))
    except ValueError:
        return None


def iso(d):
    return d.astimezone(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ') if d else None


def read_jsonl(path):
    with open(path, encoding='utf-8') as fh:
        for n, line in enumerate(fh):
            line = line.strip()
            if not line:
                continue
            try:
                yield n, json.loads(line)
            except json.JSONDecodeError:
                # a transcript that is being written can end in a partial line
                continue


def load_yaml(path):
    """PyYAML when present; otherwise a minimal parser for the nested-map / scalar subset prices.yaml uses."""
    try:
        import yaml  # type: ignore
        with open(path, encoding='utf-8') as fh:
            return yaml.safe_load(fh)
    except ImportError:
        pass
    root: dict = {}
    stack = [(-1, root)]
    with open(path, encoding='utf-8') as fh:
        for raw in fh:
            line = raw.split(' #', 1)[0].rstrip() if not raw.lstrip().startswith('#') else ''
            if not line.strip():
                continue
            indent = len(line) - len(line.lstrip())
            key, _, val = line.strip().partition(':')
            val = val.strip()
            while stack[-1][0] >= indent:
                stack.pop()
            parent = stack[-1][1]
            if val == '':
                parent[key] = {}
                stack.append((indent, parent[key]))
                continue
            if val in ('null', '~'):
                v = None
            elif val[:1] in '"\'':
                v = val[1:-1]
            else:
                try:
                    v = float(val) if any(c in val for c in '.eE') else int(val)
                except ValueError:
                    v = val
            parent[key] = v
    return root


def git(*args):
    try:
        return subprocess.run(['git', '-C', REPO, *args], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ''


# ----------------------------------------------------------------------------------------------- pricing
PRICE_KEYS = ('input', 'output', 'cache_write_5m', 'cache_write_1h', 'cache_read')


class Pricer:
    def __init__(self, prices):
        self.models = (prices or {}).get('models', {}) or {}

    def rates(self, model):
        p = self.models.get(model)
        if not p or any(p.get(k) is None for k in PRICE_KEYS):
            return None
        return {k: float(p[k]) for k in PRICE_KEYS}

    def cost(self, model, t):
        r = self.rates(model)
        if r is None:
            return None
        return (t['in'] * r['input'] + t['out'] * r['output'] + t['cw5m'] * r['cache_write_5m']
                + t['cw1h'] * r['cache_write_1h'] + t['cr'] * r['cache_read']) / 1e6


def zero_tokens():
    return {'in': 0, 'out': 0, 'cw': 0, 'cw5m': 0, 'cw1h': 0, 'cr': 0, 'messages': 0}


def add_tokens(acc, t):
    for k in t:
        acc[k] = acc.get(k, 0) + t[k]


def usage_tokens(u, notes):
    cw = int(u.get('cache_creation_input_tokens') or 0)
    split = u.get('cache_creation') or {}
    cw5 = int(split.get('ephemeral_5m_input_tokens') or 0)
    cw1 = int(split.get('ephemeral_1h_input_tokens') or 0)
    if cw5 + cw1 != cw:
        # unsplit remainder priced at the 5-minute write rate (Claude Code's default TTL); counted and reported
        notes['cache_write_unsplit_tokens'] += cw - cw5 - cw1
        cw5 = cw - cw1
    return {'in': int(u.get('input_tokens') or 0), 'out': int(u.get('output_tokens') or 0), 'cw': cw,
            'cw5m': cw5, 'cw1h': cw1, 'cr': int(u.get('cache_read_input_tokens') or 0), 'messages': 1}


# ----------------------------------------------------------------------------------------------- discovery
def phase_of(wf_name, stage, journal_phase, label, desc=None, is_main=False):
    if is_main:
        return 'main-session'
    if desc is not None:
        for rx, ph in DESC_PHASE:
            if rx.search(desc or ''):
                return ph
        return 'other'
    if wf_name in ('wsi-plan-slice', 'wsi-viewer-plan'):
        if stage in VERIFY_STAGES or journal_phase == 'Verify' or (label or '').startswith(('verify', 'extract-claims')):
            return 'verification'
        return 'planning'
    if wf_name in WF_PHASE:
        return WF_PHASE[wf_name]
    for rx, ph in LABEL_PHASE:
        if rx.search(label or ''):
            return ph
    return 'other'


def discover(projects):
    sessions = []
    for main in sorted(glob.glob(os.path.join(projects, '*.jsonl'))):
        sid = os.path.basename(main)[:-6]
        sdir = os.path.join(projects, sid)
        wf_json = {}
        for f in sorted(glob.glob(os.path.join(sdir, 'workflows', 'wf_*.json'))):
            try:
                wf_json[os.path.basename(f)[:-5]] = json.load(open(f, encoding='utf-8'))
            except Exception:
                pass
        journals = {}
        for jp in sorted(glob.glob(os.path.join(sdir, 'subagents', 'workflows', '*', 'journal.jsonl'))):
            wf = os.path.basename(os.path.dirname(jp))
            journals[wf] = [r for _, r in read_jsonl(jp)]
        agent_files = collections.defaultdict(list)
        for f in sorted(glob.glob(os.path.join(sdir, 'subagents', '**', 'agent-*.jsonl'), recursive=True)):
            agent_files[os.path.basename(f)[len('agent-'):-len('.jsonl')]].append(f)
        metas = {}
        for f in sorted(glob.glob(os.path.join(sdir, 'subagents', '**', 'agent-*.meta.json'), recursive=True)):
            aid = os.path.basename(f)[len('agent-'):-len('.meta.json')]
            try:
                m = json.load(open(f, encoding='utf-8'))
            except Exception:
                continue
            # keep the richest record (the top-level copy of a backgrounded workflow agent has no description)
            if aid not in metas or len(m) > len(metas[aid]):
                metas[aid] = m
        sessions.append({'sid': sid, 'main': main, 'wf_json': wf_json, 'journals': journals,
                         'agent_files': agent_files, 'metas': metas})
    return sessions


# ----------------------------------------------------------------------------------------------- main pass
def rollup(projects, pricer, as_of):
    sessions = discover(projects)
    single = len(sessions) == 1
    seen_msg = {}                      # message.id -> (run_id, file) that counted it
    cross_file = set()                 # message ids recorded in more than one file
    msg_log = []                       # (timestamp, model, tokens) per counted response, for the harness cross-check
    notes = collections.Counter()
    runs = []
    owner_msgs, owner_cmds = [], []
    cost_state = None
    files_scanned = 0
    lines_scanned = 0

    def scan(files, run_id, owner=False):
        nonlocal files_scanned, lines_scanned, cost_state
        tok_by_model = collections.defaultdict(zero_tokens)
        first = last = None
        synthetic = dup_lines = dup_cross = 0
        for f in files:
            files_scanned += 1
            for _, r in read_jsonl(f):
                lines_scanned += 1
                t = ts(r.get('timestamp'))
                if t:
                    first = t if first is None or t < first else first
                    last = t if last is None or t > last else last
                typ = r.get('type')
                if owner and typ == 'cost-state':
                    cost_state = dict(r, _last_ts=iso(last))   # the record carries no timestamp: use the line before it
                if owner and typ == 'user' and not r.get('toolUseResult'):
                    origin = r.get('origin') or {}
                    content = (r.get('message') or {}).get('content')
                    if origin.get('kind') == 'human':
                        owner_msgs.append(r.get('timestamp'))
                    elif isinstance(content, str) and content.lstrip().startswith('<command-name>'):
                        owner_cmds.append(r.get('timestamp'))
                if typ != 'assistant':
                    continue
                m = r.get('message') or {}
                mid = m.get('id') or r.get('requestId') or r.get('uuid')
                if mid in seen_msg:
                    dup_lines += 1
                    if seen_msg[mid][1] != f:
                        cross_file.add(mid)
                    if seen_msg[mid][0] != run_id:
                        dup_cross += 1
                    continue
                seen_msg[mid] = (run_id, f)
                model = m.get('model') or 'unknown'
                u = m.get('usage') or {}
                if model == '<synthetic>':
                    synthetic += 1
                    if any(int(u.get(k) or 0) for k in ('input_tokens', 'output_tokens', 'cache_creation_input_tokens', 'cache_read_input_tokens')):
                        notes['synthetic_with_usage'] += 1
                    continue
                ut = usage_tokens(u, notes)
                add_tokens(tok_by_model[model], ut)
                msg_log.append((t, model, ut))
        notes['duplicate_lines_same_message'] += dup_lines
        notes['duplicate_messages_across_runs'] += dup_cross
        return tok_by_model, first, last, synthetic

    for s in sessions:
        sid = s['sid']
        main_id = 'main' if single else f'main:{sid[:8]}'
        # ---- workflow agents (journal is the authority for label, phase and outcome)
        agent_wf = {}
        for wf, recs in s['journals'].items():
            for r in recs:
                if r.get('type') == 'started':
                    agent_wf[r['agentId']] = (wf, r)
        jterm = {}
        for wf, recs in s['journals'].items():
            for r in recs:
                if r.get('type') in ('result', 'failed') and r.get('agentId'):
                    jterm[r['agentId']] = r['type']
        records = []
        # main session first (its transcript holds the owner's messages and the harness cost-state)
        tok, first, last, syn = scan([s['main']], main_id, owner=True)
        records.append(dict(run_id=main_id, session_id=sid, kind='main', parent=None, role='main session (orchestrator)',
                            journal_phase=None, phase='main-session', workflow=None, workflow_name=None, workflow_stage=None,
                            tok=tok, first=first, last=last, synthetic=syn, outcome='in_progress',
                            outcome_source='interactive session; no terminal record', files=[s['main']]))
        for aid in sorted(s['agent_files']):
            files = s['agent_files'][aid]
            meta = s['metas'].get(aid, {})
            tok, first, last, syn = scan(files, aid)
            if aid in agent_wf:
                wf, st = agent_wf[aid]
                wj = s['wf_json'].get(wf, {})
                name = wj.get('workflowName')
                stage = (wj.get('args') or {}).get('stage') if isinstance(wj.get('args'), dict) else None
                if aid in jterm:
                    outcome, src = ('result' if jterm[aid] == 'result' else 'error'), f'journal {jterm[aid]} record'
                elif wj.get('status') == 'killed':
                    outcome, src = 'killed', 'no journal result; workflow status killed'
                elif not wj:
                    outcome, src = 'in_progress', 'no journal result; workflow record not written yet (running at roll-up)'
                else:
                    outcome, src = 'killed', f"no journal result; workflow status {wj.get('status')}"
                records.append(dict(run_id=aid, session_id=sid, kind='workflow-agent', parent=wf, role=st.get('label'),
                                    journal_phase=st.get('phase'),
                                    phase=phase_of(name, stage, st.get('phase'), st.get('label')),
                                    workflow=wf, workflow_name=name, workflow_stage=stage, tok=tok, first=first, last=last,
                                    synthetic=syn, outcome=outcome, outcome_source=src, files=files))
            else:
                desc = meta.get('description') or ''
                if meta.get('finished'):
                    outcome, src = 'result', 'meta.finished = true'
                else:
                    outcome, src = 'killed', 'meta.finished absent (ended without a final report)'
                records.append(dict(run_id=aid, session_id=sid, kind='direct-subagent', parent=main_id, role=desc or None,
                                    journal_phase=None, phase=phase_of(None, None, None, None, desc=desc),
                                    workflow=None, workflow_name=None, workflow_stage=None, tok=tok, first=first,
                                    last=last, synthetic=syn, outcome=outcome, outcome_source=src, files=files))
        for rec in records:
            runs.append(finish_run(rec, pricer, projects))
        s['main_id'] = main_id
    runs.sort(key=lambda r: (r['started_at'] or '', r['run_id']))
    notes['duplicate_messages_across_files'] = len(cross_file)
    totals = aggregate(runs, sessions, pricer, notes, owner_msgs, owner_cmds, cost_state, as_of,
                       files_scanned, lines_scanned, len(seen_msg), msg_log)
    return runs, totals


def finish_run(rec, pricer, projects):
    tok = rec['tok']
    models = sorted(tok)
    tot = zero_tokens()
    for m in models:
        add_tokens(tot, tok[m])
    cost_by_model, unpriced = {}, []
    for m in models:
        c = pricer.cost(m, tok[m])
        if c is None:
            unpriced.append(m)
            cost_by_model[m] = 'unpriced'
        else:
            cost_by_model[m] = round(c, 6)
    cost = 'unpriced' if unpriced else round(sum(v for v in cost_by_model.values()), 6)
    first, last = rec['first'], rec['last']
    return {
        'run_id': rec['run_id'],
        'session_id': rec['session_id'],
        'kind': rec['kind'],
        'parent': rec['parent'] if rec['parent'] is not None else None,
        'role': rec['role'],
        'journal_phase': rec['journal_phase'],
        'phase': rec['phase'],
        'workflow_name': rec['workflow_name'],
        'workflow_stage': rec['workflow_stage'],
        'model_id': (models[0] if len(models) == 1 else ('mixed' if models else None)),
        'models': models,
        'api_messages': tot['messages'],
        'synthetic_messages': rec['synthetic'],
        'tokens_in': tot['in'],
        'tokens_out': tot['out'],
        'tokens_cache_write': tot['cw'],
        'tokens_cache_write_5m': tot['cw5m'],
        'tokens_cache_write_1h': tot['cw1h'],
        'tokens_cache_read': tot['cr'],
        'tokens_by_model': {m: {k: tok[m][k] for k in ('in', 'out', 'cw', 'cw5m', 'cw1h', 'cr', 'messages')} for m in models},
        'started_at': iso(first),
        'ended_at': iso(last),
        'wall_clock_s': round((last - first).total_seconds(), 1) if first and last else None,
        'outcome': rec['outcome'],
        'outcome_source': rec['outcome_source'],
        'cost_usd': cost,
        'cost_by_model_usd': cost_by_model,
        'cost_basis': 'list price (prices.yaml); subscription plan in use, so this is comparable API cost, not money spent',
        'human_minutes': None,
        'human_role': None,
        'source_files': [os.path.relpath(f, projects) for f in rec['files']],
    }


# ----------------------------------------------------------------------------------------------- aggregation
def union_seconds(intervals):
    iv = sorted((a, b) for a, b in intervals if a and b)
    total, cur = 0.0, None
    for a, b in iv:
        if cur is None or a > cur[1]:
            if cur:
                total += (cur[1] - cur[0]).total_seconds()
            cur = [a, b]
        elif b > cur[1]:
            cur[1] = b
    if cur:
        total += (cur[1] - cur[0]).total_seconds()
    return total


def aggregate(runs, sessions, pricer, notes, owner_msgs, owner_cmds, cost_state, as_of, nfiles, nlines, nmsgs, msg_log):
    by_model = collections.defaultdict(zero_tokens)
    for r in runs:
        for m, t in r['tokens_by_model'].items():
            add_tokens(by_model[m], t)
    model_rows = {}
    total_cost, unpriced_models = 0.0, []
    for m, t in sorted(by_model.items()):
        c = pricer.cost(m, t)
        model_rows[m] = dict(t, cost_usd=(round(c, 2) if c is not None else 'unpriced'))
        if c is None:
            unpriced_models.append(m)
        else:
            total_cost += c

    def phase_row(sel):
        t = zero_tokens()
        cost, unp = 0.0, False
        for r in sel:
            t['in'] += r['tokens_in']; t['out'] += r['tokens_out']; t['cw'] += r['tokens_cache_write']
            t['cr'] += r['tokens_cache_read']; t['messages'] += r['api_messages']
            if isinstance(r['cost_usd'], (int, float)):
                cost += r['cost_usd']
            else:
                unp = True
        starts = [ts(r['started_at']) for r in sel if r['started_at']]
        ends = [ts(r['ended_at']) for r in sel if r['ended_at']]
        return {
            'runs': len(sel), 'outcomes': dict(collections.Counter(r['outcome'] for r in sel)),
            'tokens_in': t['in'], 'tokens_out': t['out'], 'tokens_cache_write': t['cw'], 'tokens_cache_read': t['cr'],
            'api_messages': t['messages'], 'cost_usd': round(cost, 2), 'has_unpriced': unp,
            'first_start': iso(min(starts)) if starts else None, 'last_end': iso(max(ends)) if ends else None,
            'agent_wall_clock_h': round(sum(r['wall_clock_s'] or 0 for r in sel) / 3600, 2),
            'workflows': sorted({r['parent'] for r in sel if r['kind'] == 'workflow-agent'}),
        }

    phases = {p: phase_row([r for r in runs if r['phase'] == p]) for p in PHASES + ['other']}
    phases = {p: v for p, v in phases.items() if v['runs']}
    for p, v in phases.items():
        v['workflow_count'] = len(v.pop('workflows'))

    wf_rows = {}
    for s in sessions:
        for wf, wj in s['wf_json'].items():
            sel = [r for r in runs if r['parent'] == wf]
            row = phase_row(sel)
            row.pop('workflows')
            row.update(workflow_name=wj.get('workflowName'), stage=(wj.get('args') or {}).get('stage') if isinstance(wj.get('args'), dict) else None,
                       status=wj.get('status'), harness_total_tokens=wj.get('totalTokens'),
                       harness_duration_s=round((wj.get('durationMs') or 0) / 1000, 1))
            wf_rows[wf] = row
        for wf in s['journals']:
            if wf not in wf_rows:
                sel = [r for r in runs if r['parent'] == wf]
                row = phase_row(sel)
                row.pop('workflows')
                row.update(workflow_name=None, stage=None, status='running (no workflow record yet)')
                wf_rows[wf] = row

    starts = [ts(r['started_at']) for r in runs if r['started_at']]
    ends = [ts(r['ended_at']) for r in runs if r['ended_at']]
    first, last = (min(starts), max(ends)) if starts else (None, None)
    agent_iv = [(ts(r['started_at']), ts(r['ended_at'])) for r in runs if r['kind'] != 'main']
    active_days = sorted({d for r in runs if r['kind'] != 'main' for d in
                          ([r['started_at'][:10], r['ended_at'][:10]] if r['started_at'] else [])})

    # first research-note date from git (author date of the first commit touching docs/research)
    research_first = git('log', '--reverse', '--format=%aI', '--', 'wsi-viewer/docs/research').splitlines()
    research_first = research_first[0] if research_first else None
    as_of_d = dt.date.fromisoformat(as_of)
    days = None
    if research_first:
        d0 = dt.date.fromisoformat(research_first[:10])
        days = {'first_research_note_commit': research_first, 'to_date': as_of,
                'elapsed_days': (as_of_d - d0).days, 'calendar_days_inclusive': (as_of_d - d0).days + 1}

    owner = sorted(t for t in owner_msgs if t)
    per_day = collections.Counter(t[:10] for t in owner)
    cmds = sorted(t for t in owner_cmds if t)

    harness = None
    if cost_state:
        mu = cost_state.get('modelUsage') or {}
        cut = ts(cost_state.get('_last_ts'))
        same = collections.defaultdict(zero_tokens)
        for t_, m_, ut in msg_log:
            if t_ and cut and t_ <= cut:
                add_tokens(same[m_], ut)
        ledger_same = {}
        for m_, tk_ in sorted(same.items()):
            c_ = pricer.cost(m_, tk_)
            ledger_same[m_] = {'output': tk_['out'], 'cache_write': tk_['cw'], 'cache_read': tk_['cr'],
                               'cost_usd': round(c_, 2) if c_ is not None else 'unpriced'}
        harness = {
            'note': "Claude Code's own running total for the session (last cost-state record in the main transcript); "
                    'it includes model calls made inside tools (e.g. web search / fetch on Haiku 5.5) and any call whose '
                    'response was never written to a transcript, so it is the upper reference and the ledger the lower bound',
            'record_written_after': cost_state.get('_last_ts'),
            'total_cost_usd': round(cost_state.get('totalCostUSD') or 0, 2),
            'ledger_same_cutoff': ledger_same,
            'models': {m: {'input': v.get('inputTokens'), 'output': v.get('outputTokens'),
                           'cache_write': v.get('cacheCreationInputTokens'), 'cache_read': v.get('cacheReadInputTokens'),
                           'web_search_requests': v.get('webSearchRequests'), 'cost_usd': round(v.get('costUSD') or 0, 2)}
                       for m, v in sorted(mu.items())},
        }

    n_kind = collections.Counter(r['kind'] for r in runs)
    tot_in = sum(r['tokens_in'] for r in runs)
    tot_out = sum(r['tokens_out'] for r in runs)
    tot_cw = sum(r['tokens_cache_write'] for r in runs)
    tot_cr = sum(r['tokens_cache_read'] for r in runs)
    return {
        'generated_at': iso(dt.datetime.now(dt.timezone.utc)),
        'as_of': as_of,
        'inputs': {'transcript_files': nfiles, 'transcript_lines': nlines, 'unique_assistant_messages': nmsgs,
                   'sessions': len(sessions), 'workflows': sum(len(s['journals']) for s in sessions),
                   'duplicate_lines_same_message': notes['duplicate_lines_same_message'],
                   'duplicate_messages_across_runs': notes['duplicate_messages_across_runs'],
                   'duplicate_messages_across_files': notes['duplicate_messages_across_files'],
                   'cache_write_unsplit_tokens': notes['cache_write_unsplit_tokens'],
                   'synthetic_with_usage': notes['synthetic_with_usage']},
        'runs': {'total': len(runs), 'by_kind': dict(n_kind), 'outcomes': dict(collections.Counter(r['outcome'] for r in runs))},
        'tokens': {'in': tot_in, 'out': tot_out, 'in_plus_out': tot_in + tot_out, 'cache_write': tot_cw, 'cache_read': tot_cr,
                   'all_kinds': tot_in + tot_out + tot_cw + tot_cr},
        'by_model': model_rows,
        'cost_usd_total': round(total_cost, 2),
        'unpriced_models': unpriced_models,
        'phases': phases,
        'workflows': wf_rows,
        'wall_clock': {'first': iso(first), 'last': iso(last),
                       'span_h': round((last - first).total_seconds() / 3600, 1) if first else None,
                       'span_days': round((last - first).total_seconds() / 86400, 2) if first else None,
                       'agent_active_union_h': round(union_seconds(agent_iv) / 3600, 1),
                       'agent_wall_clock_sum_h': round(sum(r['wall_clock_s'] or 0 for r in runs if r['kind'] != 'main') / 3600, 1),
                       'agent_active_dates': active_days},
        'days': days,
        'owner_messages': {'count': len(owner), 'per_day': dict(sorted(per_day.items())), 'timestamps': owner,
                           'slash_commands': {'count': len(cmds), 'timestamps': cmds},
                           'rule': 'type user, origin.kind == "human" in the main transcript; tool results, system, meta, '
                                   'task-notification and peer-agent text excluded; content not read into this file'},
        'harness_cost_state': harness,
        'human_minutes': None,
    }


