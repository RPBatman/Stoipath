def update_readme(path, block):
    text = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        text = pre + BEGIN + '\n' + block + '\n' + END + post
    else:
        text = text.rstrip() + '\n\n' + BEGIN + '\n' + block + '\n' + END + '\n'
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)


def parse_cutoff(text):
    d = ts(text)
    if d is None:
        raise SystemExit(f'--cutoff {text!r} is not an ISO timestamp such as 2026-11-10T20:30:00Z')
    return d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--projects', default=DEFAULT_PROJECTS, help='Claude Code project directory (default %(default)s)')
    ap.add_argument('--out-dir', default=DEFAULT_OUT, help='where runs.jsonl / totals.json go (default %(default)s)')
    ap.add_argument('--prices', default=None, help='prices.yaml (default <out-dir>/prices.yaml)')
    ap.add_argument('--cutoff', default=None,
                    help='ISO timestamp: ignore transcript lines later than this (default: now, to the minute). It is the "as of" of every figure')
    ap.add_argument('--as-of', default=None, help='roll-up date for the days count (default: the date of the cut-off)')
    ap.add_argument('--readme', action='store_true', help='refresh the generated block in <out-dir>/README.md')
    ap.add_argument('--print', action='store_true', help='print the Markdown block to stdout')
    ap.add_argument('--allow-unpriced', action='store_true',
                    help='write the ledger even when a model has no price (marked INCOMPLETE everywhere); the default is to stop with status 2')
    ap.add_argument('--allow-unmapped', action='store_true',
                    help='put workflows missing from WF_DELIVERABLE in an "unmapped" row; the default is to stop with status 3')
    a = ap.parse_args(argv)
    prices_path = a.prices or os.path.join(a.out_dir, 'prices.yaml')
    with open(prices_path, 'rb') as fh:
        sha = hashlib.sha256(fh.read()).hexdigest()
    pricer = Pricer(load_yaml(prices_path), sha256=sha)
    cutoff = parse_cutoff(a.cutoff) if a.cutoff else dt.datetime.now(dt.timezone.utc).replace(second=0, microsecond=0)
    as_of = a.as_of or cutoff.date().isoformat()
    try:
        runs, totals = rollup(a.projects, pricer, as_of, cutoff=cutoff, allow_unmapped=a.allow_unmapped)
    except LedgerError as e:
        print(f'ERROR: {e}', file=sys.stderr)
        return e.exit_code
    if totals['unpriced_models']:
        msg = ('UNPRICED MODEL(S): ' + ', '.join(totals['unpriced_models']) + ' have tokens in the transcripts but no complete row in '
               f'{prices_path}; every cost figure would be too low.')
        if not a.allow_unpriced:
            print('ERROR: ' + msg + ' Nothing was written. Add the price rows (source and date) and re-run, or pass --allow-unpriced '
                  'to write an INCOMPLETE ledger.', file=sys.stderr)
            return UnpricedModels.exit_code
        print('WARNING: ' + msg + ' Writing an INCOMPLETE ledger (--allow-unpriced).', file=sys.stderr)
    os.makedirs(a.out_dir, exist_ok=True)
    with open(os.path.join(a.out_dir, 'runs.jsonl'), 'w', encoding='utf-8') as fh:
        for r in runs:
            fh.write(json.dumps(r, sort_keys=False) + '\n')
    with open(os.path.join(a.out_dir, 'totals.json'), 'w', encoding='utf-8') as fh:
        json.dump(totals, fh, indent=1)
        fh.write('\n')
    block = render(totals)
    if a.readme:
        update_readme(os.path.join(a.out_dir, 'README.md'), block)
    if a.print:
        print(block)
    print(f"agent_runs_with_model_calls={totals['runs']['agent_runs_that_called_a_model']} lines={totals['runs']['total']} "
          f"tokens_in+out={totals['tokens']['in_plus_out']} cost_usd={totals['cost_usd_total']} "
          f"cost_complete={totals['cost_complete']} -> {a.out_dir}", file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
