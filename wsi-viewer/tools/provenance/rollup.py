def union_seconds(intervals):
    iv = sorted((a, b) for a, b in intervals if a and b)
    total, cur = 0.0, None
    for a, b in iv:
        if cur is None or a > cur[1]:
            if cur:
                total += (cur[1] - cur[0]).total_seconds()
            cur = [a, b]
        elif b > cur[1]:
            cur[1] = b
    if cur:
        total += (cur[1] - cur[0]).total_seconds()
    return total


def sum_costs(runs):
    return sum(r['cost_usd'] for r in runs)


def agg_rows(sel):
    """Counts, tokens, cost and wall-clock of a set of runs."""
    t = zero_tokens()
    for r in sel:
        t['in'] += r['tokens_in']; t['out'] += r['tokens_out']; t['cw'] += r['tokens_cache_write']
        t['cr'] += r['tokens_cache_read']; t['messages'] += r['api_messages']
    starts = [ts(r['started_at']) for r in sel if r['started_at']]
    ends = [ts(r['ended_at']) for r in sel if r['ended_at']]
    bad = [r for r in sel if r['outcome'] in ('error', 'killed')]
    return {
        'runs': len(sel), 'runs_that_called_a_model': sum(1 for r in sel if r['called_model']),
        'outcomes': dict(collections.Counter(r['outcome'] for r in sel)),
        'tokens_in': t['in'], 'tokens_out': t['out'], 'tokens_cache_write': t['cw'], 'tokens_cache_read': t['cr'],
        'api_messages': t['messages'], 'cost_usd': round(sum_costs(sel), 2),
        'failed_or_killed_runs': len(bad), 'failed_or_killed_cost_usd': round(sum_costs(bad), 2),
        'has_unpriced': any(not r['cost_complete'] for r in sel),
        'first_start': iso(min(starts)) if starts else None, 'last_end': iso(max(ends)) if ends else None,
        'agent_wall_clock_h': round(sum(r['wall_clock_s'] or 0 for r in sel) / 3600, 2),
    }


def aggregate(runs, sessions, pricer, notes, owner_msgs, owner_cmds, cost_state, as_of, nfiles, nlines, nmsgs, msg_log,
              cutoff=None, limit_texts=None, unmapped=None):
    by_model = collections.defaultdict(zero_tokens)
    for r in runs:
        for m, t in r['tokens_by_model'].items():
            add_tokens(by_model[m], t)
    model_rows = {}
    total_cost, unpriced_models = 0.0, []
    kind_cost = collections.Counter()
    uncached_equiv = 0.0
    for m, t in sorted(by_model.items()):
        c = pricer.cost(m, t)
        rates = pricer.rates(m)
        model_rows[m] = dict(t, cost_usd=(round(c, 2) if c is not None else 'unpriced'))
        if c is None:
            unpriced_models.append(m)
        else:
            total_cost += c
            kind_cost['input'] += t['in'] * rates['input'] / 1e6
            kind_cost['output'] += t['out'] * rates['output'] / 1e6
            kind_cost['cache_write'] += (t['cw5m'] * rates['cache_write_5m'] + t['cw1h'] * rates['cache_write_1h']) / 1e6
            kind_cost['cache_read'] += t['cr'] * rates['cache_read'] / 1e6
            uncached_equiv += ((t['in'] + t['cw'] + t['cr']) * rates['input'] + t['out'] * rates['output']) / 1e6
    for m, row in model_rows.items():
        if not isinstance(row['cost_usd'], str) and total_cost:
            row['share_of_cost'] = round(row['cost_usd'] / total_cost, 4)

    # ---- deliverables (the per-deliverable cost table); the sums must agree with the per-model total to the cent
    keys = [k for k, _ in DELIVERABLES] + (['unmapped'] if any(r['deliverable'] == 'unmapped' for r in runs) else [])
    deliverables = {}
    for k in keys:
        sel = [r for r in runs if r['deliverable'] == k]
        if sel:
            row = agg_rows(sel)
            row['label'] = DELIVERABLE_LABEL.get(k, 'Unmapped workflows')
            row['workflow_count'] = len({r['parent'] for r in sel if r['kind'] == 'workflow-agent'})
            row['share_of_cost'] = round(row['cost_usd'] / total_cost, 4) if total_cost else None
            deliverables[k] = row
    run_cost = sum_costs(runs)
    deliv_cost = sum(sum_costs([r for r in runs if r['deliverable'] == k]) for k in deliverables)
    if abs(run_cost - total_cost) > 0.005 or abs(deliv_cost - total_cost) > 0.005:
        raise InconsistentTotals(f'cost does not add up: per model {total_cost:.4f}, per run {run_cost:.4f}, '
                                 f'per deliverable {deliv_cost:.4f}')
    if sum(v['runs'] for v in deliverables.values()) != len(runs):
        raise InconsistentTotals('a run has no deliverable row')

    wf_rows = {}
    for s in sessions:
        for wf, wj in s['wf_json'].items():
            sel = [r for r in runs if r['parent'] == wf]
            if not sel:
                continue
            row = agg_rows(sel)
            row.update(workflow_name=wj.get('workflowName'), stage=(wj.get('args') or {}).get('stage') if isinstance(wj.get('args'), dict) else None,
                       status=wj.get('status'), deliverable=sel[0]['deliverable'], harness_total_tokens=wj.get('totalTokens'),
                       harness_duration_s=round((wj.get('durationMs') or 0) / 1000, 1))
            wf_rows[wf] = row
        for wf in s['journals']:
            if wf not in wf_rows:
                sel = [r for r in runs if r['parent'] == wf]
                if not sel:
                    continue
                row = agg_rows(sel)
                row.update(workflow_name=s['script_names'].get(wf), stage=None, status='running (no workflow record yet)',
                           deliverable=sel[0]['deliverable'])
                wf_rows[wf] = row

    agents = [r for r in runs if r['kind'] != 'main']
    starts = [ts(r['started_at']) for r in runs if r['started_at']]
    ends = [ts(r['ended_at']) for r in runs if r['ended_at']]
    first, last = (min(starts), max(ends)) if starts else (None, None)
    agent_iv = [(ts(r['started_at']), ts(r['ended_at'])) for r in agents]
    active_days = sorted({d for r in agents for d in ([r['started_at'][:10], r['ended_at'][:10]] if r['started_at'] else [])})

    # first research-note date from git (author date of the first commit touching docs/research)
    research_first = git('log', '--reverse', '--format=%aI', '--', 'wsi-viewer/docs/research').splitlines()
    research_first = research_first[0] if research_first else None
    as_of_d = dt.date.fromisoformat(as_of)
    days = None
    if research_first:
        d0 = dt.date.fromisoformat(research_first[:10])
        days = {'first_research_note_commit': research_first, 'to_date': as_of,
                'elapsed_days': (as_of_d - d0).days, 'calendar_days_inclusive': (as_of_d - d0).days + 1}

    owner = sorted(t for t in owner_msgs if t)
    per_day = collections.Counter(t[:10] for t in owner)
    cmds = sorted(t for t in owner_cmds if t)
    cmd_per_day = collections.Counter(t[:10] for t in cmds)

    harness = None
    if cost_state:
        mu = cost_state.get('modelUsage') or {}
        cut = ts(cost_state.get('_last_ts'))
        same = collections.defaultdict(zero_tokens)
        for t_, m_, ut in msg_log:
            if t_ and cut and t_ <= cut:
                add_tokens(same[m_], ut)
        ledger_same = {}
        for m_, tk_ in sorted(same.items()):
            c_ = pricer.cost(m_, tk_)
            ledger_same[m_] = {'output': tk_['out'], 'cache_write': tk_['cw'], 'cache_read': tk_['cr'],
                               'cost_usd': round(c_, 2) if c_ is not None else 'unpriced'}
        hmodels = {}
        for m, v in sorted(mu.items()):
            reqs = int(v.get('webSearchRequests') or 0)
            fee = round(reqs * pricer.web_search_per_1000 / 1000, 2) if pricer.web_search_per_1000 is not None else None
            hc = round(v.get('costUSD') or 0, 2)
            hmodels[m] = {'input': v.get('inputTokens'), 'output': v.get('outputTokens'),
                          'cache_write': v.get('cacheCreationInputTokens'), 'cache_read': v.get('cacheReadInputTokens'),
                          'web_search_requests': reqs, 'web_search_fee_usd': fee, 'cost_usd': hc,
                          'token_cost_usd': round(hc - fee, 2) if fee is not None else None}
        h_total = round(cost_state.get('totalCostUSD') or 0, 2)
        comparable = [m for m in hmodels if m in ledger_same and isinstance(ledger_same[m]['cost_usd'], (int, float))]
        harness = {
            'note': "Claude Code's own running total for the session (last cost-state record in the main transcript); it includes "
                    'model calls made inside tools (web search and fetch, run by a small model), web-search fees, and any call whose '
                    'response was never written to a transcript, so it is the upper reference and the ledger the lower bound',
            'record_written_after': cost_state.get('_last_ts'),
            'total_cost_usd': h_total,
            'ledger_same_cutoff': ledger_same,
            'ledger_same_cutoff_total_usd': round(sum(v['cost_usd'] for v in ledger_same.values() if isinstance(v['cost_usd'], (int, float))), 2),
            'ledger_at_or_below_harness_in_every_model_row': all(ledger_same[m]['cost_usd'] <= hmodels[m]['cost_usd'] + 0.005 for m in comparable),
            'models_in_harness_not_in_ledger': sorted(m for m in hmodels if m not in ledger_same),
            'models': hmodels,
            'web_search_requests_total': sum(v['web_search_requests'] for v in hmodels.values()),
            'web_search_fee_usd_total': round(sum(v['web_search_fee_usd'] or 0 for v in hmodels.values()), 2),
        }

    n_kind = collections.Counter(r['kind'] for r in runs)
    tot_in = sum(r['tokens_in'] for r in runs)
    tot_out = sum(r['tokens_out'] for r in runs)
    tot_cw = sum(r['tokens_cache_write'] for r in runs)
    tot_cr = sum(r['tokens_cache_read'] for r in runs)
    zero_call = [r for r in agents if not r['called_model']]
    superseded = [r for r in runs if r['superseded_by']]
    outcomes = {}
    for o in ('result', 'error', 'killed', 'in_progress'):
        sel = [r for r in runs if r['outcome'] == o]
        if sel:
            outcomes[o] = {'runs': len(sel), 'cost_usd': round(sum_costs(sel), 2), 'share_of_cost': round(sum_costs(sel) / total_cost, 4) if total_cost else None}
    bad = [r for r in runs if r['outcome'] in ('error', 'killed')]
    cost_complete = not unpriced_models and not any(not r['cost_complete'] for r in runs)
    totals = {
        'generated_at': iso(dt.datetime.now(dt.timezone.utc)),
        'as_of': as_of,
        'as_of_utc': iso(cutoff) if cutoff else None,
        'inputs': {'transcript_files': nfiles, 'transcript_lines': nlines, 'unique_assistant_messages': nmsgs,
                   'sessions': len(sessions), 'workflows': sum(1 for s in sessions for wf in s['journals'] if any(r['parent'] == wf for r in runs)),
                   'duplicate_lines_same_message': notes['duplicate_lines_same_message'],
                   'duplicate_messages_across_runs': notes['duplicate_messages_across_runs'],
                   'duplicate_messages_across_files': notes['duplicate_messages_across_files'],
                   'cache_write_unsplit_tokens': notes['cache_write_unsplit_tokens'],
                   'synthetic_with_usage': notes['synthetic_with_usage']},
        'runs': {'total': len(runs),
                 'definition': 'agent run = one subagent (workflow agent or direct subagent); the interactive main session is counted '
                               'separately; "called a model" = at least one API response with usage in its transcript',
                 'agent_launches': len(agents),
                 'agent_runs_that_called_a_model': len(agents) - len(zero_call),
                 'agent_launches_without_a_model_call': len(zero_call),
                 'main_session': n_kind.get('main', 0),
                 'by_kind': dict(n_kind), 'outcomes': dict(collections.Counter(r['outcome'] for r in runs))},
        'outcomes_cost': outcomes,
        'failed_or_killed': {'runs': len(bad), 'cost_usd': round(sum_costs(bad), 2),
                             'share_of_cost': round(sum_costs(bad) / total_cost, 4) if total_cost else None,
                             'rule': 'outcome error (journal failed record) or killed (agent started, no result record); '
                                     'a killed run can still have produced files, so this is an upper bound of work not delivered by that run'},
        'usage_limits': {'launches_refused_without_a_model_call': sum(1 for r in zero_call if r['usage_limit_records']),
                         'refused_launches_by_start_date': dict(sorted(collections.Counter(
                             r['started_at'][:10] for r in zero_call if r['usage_limit_records']).items())),
                         'launches_without_a_model_call_and_no_limit_record': sum(1 for r in zero_call if not r['usage_limit_records']),
                         'runs_interrupted_after_model_calls': sum(1 for r in agents if r['called_model'] and r['usage_limit_records']),
                         'interrupted_runs_by_start_date': dict(sorted(collections.Counter(
                             r['started_at'][:10] for r in agents if r['called_model'] and r['usage_limit_records']).items())),
                         'messages': dict(limit_texts or {})},
        'resumed_workflows': {'launches_superseded_by_a_restart': len(superseded),
                              'cost_usd': round(sum_costs(superseded), 2),
                              'of_which_without_a_model_call': sum(1 for r in superseded if not r['called_model']),
                              'rule': 'an agent started again under the same journal key (the workflow was resumed): both attempts are '
                                      'kept as runs, the first has superseded_by set; no message id is shared between them'},
        'tokens': {'in': tot_in, 'out': tot_out, 'in_plus_out': tot_in + tot_out, 'cache_write': tot_cw, 'cache_read': tot_cr,
                   'all_kinds': tot_in + tot_out + tot_cw + tot_cr},
        'tool_calls': sum(r['tool_calls'] for r in runs),
        'web_search_calls_in_transcripts': sum(r['web_search_calls'] for r in runs),
        'by_model': model_rows,
        'cost_usd_total': round(total_cost, 2),
        'cost_complete': cost_complete,
        'unpriced_models': unpriced_models,
        'price_table': {'as_of': pricer.as_of, 'sha256': pricer.sha256,
                        'web_search_usd_per_1000': pricer.web_search_per_1000},
        'cost_mix': {k: {'usd': round(v, 2), 'share': round(v / total_cost, 4) if total_cost else None} for k, v in kind_cost.items()},
        'uncached_equivalent_usd': round(uncached_equiv, 2),
        'deliverables': deliverables,
        'workflows': wf_rows,
        'unmapped_workflows': dict(unmapped or {}),
        'wall_clock': {'first': iso(first), 'last': iso(last),
                       'span_h': round((last - first).total_seconds() / 3600, 1) if first else None,
                       'span_days': round((last - first).total_seconds() / 86400, 2) if first else None,
                       'agent_active_union_h': round(union_seconds(agent_iv) / 3600, 1),
                       'agent_wall_clock_sum_h': round(sum(r['wall_clock_s'] or 0 for r in agents) / 3600, 1),
                       'agent_active_dates': active_days,
                       'calendar_dates_in_span': ((last.date() - first.date()).days + 1) if first else None},
        'days': days,
        'owner_messages': {'count': len(owner), 'per_day': dict(sorted(per_day.items())),
                           'slash_commands': {'count': len(cmds), 'per_day': dict(sorted(cmd_per_day.items()))},
                           'rule': 'type user, origin.kind == "human" in the main transcript; tool results, system, meta, '
                                   'task-notification and peer-agent text excluded; content not read into this file; '
                                   'per-day counts only (no timestamps are published)'},
        'harness_cost_state': harness,
        'web_search_fees': {'requests_in_harness_record': harness['web_search_requests_total'] if harness else None,
                            'usd_per_1000': pricer.web_search_per_1000,
                            'fee_usd': harness['web_search_fee_usd_total'] if harness else None,
                            'in_ledger_total': False,
                            'note': 'web-search fees and the small-model calls inside the search and fetch tools appear only in the '
                                    "harness's aggregate record, not in any transcript message, so they are outside cost_usd_total"},
        'human_minutes': None,
    }
    totals['basis_sentence'] = basis_sentence(totals)
    return totals


def basis_sentence(t):
    """The one sentence every other document quotes verbatim."""
    n = t['runs']['agent_runs_that_called_a_model']
    floor_usd = int(t['cost_usd_total'] // 1)
    stamp = (t['as_of_utc'] or t['generated_at']).replace('T', ' ')[:16] + ' UTC'
    head = '' if t['cost_complete'] else ('INCOMPLETE, model(s) ' + ', '.join(t['unpriced_models']) + ' are not priced: ')
    return (f"{head}At API list prices (standard speed, no batch discount, prompt caching as recorded), the model usage logged in this "
            f"project's agent transcripts ({n} agent runs that each called a model, plus the main session, across all project phases) "
            f"comes to at least US${floor_usd:,} as of {stamp}; that is a lower bound (web-search fees, model calls made inside tools "
            f"and any response never written to a transcript are left out), the API-equivalent of work done on a subscription plan "
            f"and not money spent, and the human hours are not logged.")


