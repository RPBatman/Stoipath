# ----------------------------------------------------------------------------------------------- small helpers
def ts(s):
    if not s:
        return None
    try:
        return dt.datetime.fromisoformat(s.replace('Z', '+00:00'))
    except ValueError:
        return None


def iso(d):
    return d.astimezone(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ') if d else None


def read_jsonl(path):
    with open(path, encoding='utf-8') as fh:
        for n, line in enumerate(fh):
            line = line.strip()
            if not line:
                continue
            try:
                yield n, json.loads(line)
            except json.JSONDecodeError:
                # a transcript that is being written can end in a partial line
                continue


def load_yaml(path):
    """PyYAML when present; otherwise a minimal parser for the nested-map / scalar subset prices.yaml uses."""
    try:
        import yaml  # type: ignore
        with open(path, encoding='utf-8') as fh:
            return yaml.safe_load(fh)
    except ImportError:
        pass
    root: dict = {}
    stack = [(-1, root)]
    with open(path, encoding='utf-8') as fh:
        for raw in fh:
            line = raw.split(' #', 1)[0].rstrip() if not raw.lstrip().startswith('#') else ''
            if not line.strip():
                continue
            indent = len(line) - len(line.lstrip())
            key, _, val = line.strip().partition(':')
            val = val.strip()
            while stack[-1][0] >= indent:
                stack.pop()
            parent = stack[-1][1]
            if val == '':
                parent[key] = {}
                stack.append((indent, parent[key]))
                continue
            if val in ('null', '~'):
                v = None
            elif val[:1] in '"\'':
                v = val[1:-1]
            else:
                try:
                    v = float(val) if any(c in val for c in '.eE') else int(val)
                except ValueError:
                    v = val
            parent[key] = v
    return root


def git(*args):
    try:
        return subprocess.run(['git', '-C', REPO, *args], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ''


# ----------------------------------------------------------------------------------------------- pricing
PRICE_KEYS = ('input', 'output', 'cache_write_5m', 'cache_write_1h', 'cache_read')


class Pricer:
    def __init__(self, prices, sha256=None):
        prices = prices or {}
        self.models = prices.get('models', {}) or {}
        self.as_of = str(prices.get('as_of') or '')
        self.sha256 = sha256
        st = prices.get('server_tools') or {}
        self.web_search_per_1000 = float(st['web_search_usd_per_1000']) if st.get('web_search_usd_per_1000') is not None else None

    def basis(self):
        return (f"list price, prices.yaml dated {self.as_of or 'unknown'} (sha256 {(self.sha256 or 'unknown')[:12]}), "
                'applied per model; API-equivalent cost of the logged tokens, not money spent (subscription plan)')

    def rates(self, model):
        p = self.models.get(model)
        if not p or any(p.get(k) is None for k in PRICE_KEYS):
            return None
        return {k: float(p[k]) for k in PRICE_KEYS}

    def cost(self, model, t):
        r = self.rates(model)
        if r is None:
            return None
        return (t['in'] * r['input'] + t['out'] * r['output'] + t['cw5m'] * r['cache_write_5m']
                + t['cw1h'] * r['cache_write_1h'] + t['cr'] * r['cache_read']) / 1e6


def zero_tokens():
    return {'in': 0, 'out': 0, 'cw': 0, 'cw5m': 0, 'cw1h': 0, 'cr': 0, 'messages': 0}


def add_tokens(acc, t):
    for k in t:
        acc[k] = acc.get(k, 0) + t[k]


def usage_tokens(u, notes):
    cw = int(u.get('cache_creation_input_tokens') or 0)
    split = u.get('cache_creation') or {}
    cw5 = int(split.get('ephemeral_5m_input_tokens') or 0)
    cw1 = int(split.get('ephemeral_1h_input_tokens') or 0)
    if cw5 + cw1 != cw:
        # unsplit remainder priced at the 5-minute write rate (Claude Code's default TTL); counted and reported
        notes['cache_write_unsplit_tokens'] += cw - cw5 - cw1
        cw5 = cw - cw1
    return {'in': int(u.get('input_tokens') or 0), 'out': int(u.get('output_tokens') or 0), 'cw': cw,
            'cw5m': cw5, 'cw1h': cw1, 'cr': int(u.get('cache_read_input_tokens') or 0), 'messages': 1}


# ----------------------------------------------------------------------------------------------- discovery
def deliverable_of(wf_name, stage, journal_phase, label, desc=None, is_main=False):
    """Deliverable key for one run, or None when the workflow / description is not in the map."""
    if is_main:
        return 'main-session'
    if desc is not None:
        for rx, key in DESC_DELIVERABLE:
            if rx.search(desc or ''):
                return key
        return None
    if wf_name in ('wsi-plan-slice', 'wsi-viewer-plan'):
        if stage in VERIFY_STAGES or journal_phase == 'Verify' or (label or '').startswith(('verify', 'extract-claims')):
            return 'verification'
        return 'planning'
    return WF_DELIVERABLE.get(wf_name)


def discover(projects):
    sessions = []
    for main in sorted(glob.glob(os.path.join(projects, '*.jsonl'))):
        sid = os.path.basename(main)[:-6]
        sdir = os.path.join(projects, sid)
        wf_json = {}
        for f in sorted(glob.glob(os.path.join(sdir, 'workflows', 'wf_*.json'))):
            try:
                wf_json[os.path.basename(f)[:-5]] = json.load(open(f, encoding='utf-8'))
            except Exception:
                pass
        script_names = {}                  # wf id -> workflow name, from workflows/scripts/<name>-<wf id>.js
        for f in sorted(glob.glob(os.path.join(sdir, 'workflows', 'scripts', '*-wf_*.js'))):
            m = re.match(r'^(?P<name>.+)-(?P<wf>wf_[0-9a-f]+-[0-9a-f]+)\.js$', os.path.basename(f))
            if m:
                script_names[m.group('wf')] = m.group('name')
        journals = {}
        for jp in sorted(glob.glob(os.path.join(sdir, 'subagents', 'workflows', '*', 'journal.jsonl'))):
            wf = os.path.basename(os.path.dirname(jp))
            journals[wf] = [r for _, r in read_jsonl(jp)]
        agent_files = collections.defaultdict(list)
        for f in sorted(glob.glob(os.path.join(sdir, 'subagents', '**', 'agent-*.jsonl'), recursive=True)):
            agent_files[os.path.basename(f)[len('agent-'):-len('.jsonl')]].append(f)
        metas = {}
        for f in sorted(glob.glob(os.path.join(sdir, 'subagents', '**', 'agent-*.meta.json'), recursive=True)):
            aid = os.path.basename(f)[len('agent-'):-len('.meta.json')]
            try:
                m = json.load(open(f, encoding='utf-8'))
            except Exception:
                continue
            # keep the richest record (the top-level copy of a backgrounded workflow agent has no description)
            if aid not in metas or len(m) > len(metas[aid]):
                metas[aid] = m
        sessions.append({'sid': sid, 'main': main, 'wf_json': wf_json, 'journals': journals, 'script_names': script_names,
                         'agent_files': agent_files, 'metas': metas})
    return sessions


# ----------------------------------------------------------------------------------------------- main pass
def rollup(projects, pricer, as_of, cutoff=None, allow_unmapped=False):
    """Walk the transcripts. `cutoff` (aware datetime): every transcript line later than it is ignored."""
    sessions = discover(projects)
    single = len(sessions) == 1
    seen_msg = {}                      # message.id -> (run_id, file) that counted it
    seen_tool = set()                  # tool_use ids already counted
    cross_file = set()                 # message ids recorded in more than one file
    msg_log = []                       # (timestamp, model, tokens) per counted response, for the harness cross-check
    notes = collections.Counter()
    unmapped = collections.Counter()   # workflow name (or description) -> runs, for names missing from the map
    limit_texts = collections.Counter()
    runs = []
    owner_msgs, owner_cmds = [], []
    cost_state = None
    files_scanned = 0
    lines_scanned = 0

    def scan(files, run_id, owner=False):
        nonlocal files_scanned, lines_scanned, cost_state
        tok_by_model = collections.defaultdict(zero_tokens)
        first = last = None
        synthetic = dup_lines = dup_cross = tool_calls = web_searches = limit_records = 0
        cut = False                                    # True when a transcript line later than the cut-off exists
        for f in files:
            counted = False                            # a file counts as an input only if it has a line at the cut-off
            for _, r in read_jsonl(f):
                t = ts(r.get('timestamp'))
                if cutoff and t and t > cutoff:
                    cut = True
                    break                              # transcripts are append-only: nothing later belongs to this cut-off
                if not counted:
                    files_scanned += 1
                    counted = True
                lines_scanned += 1
                if t:
                    first = t if first is None or t < first else first
                    last = t if last is None or t > last else last
                typ = r.get('type')
                if owner and typ == 'cost-state':
                    cost_state = dict(r, _last_ts=iso(last))   # the record carries no timestamp: use the line before it
                if owner and typ == 'user' and not r.get('toolUseResult'):
                    origin = r.get('origin') or {}
                    content = (r.get('message') or {}).get('content')
                    if origin.get('kind') == 'human':
                        owner_msgs.append(r.get('timestamp'))
                    elif isinstance(content, str) and content.lstrip().startswith('<command-name>'):
                        owner_cmds.append(r.get('timestamp'))
                if typ != 'assistant':
                    continue
                m = r.get('message') or {}
                for blk in (m.get('content') if isinstance(m.get('content'), list) else []):
                    if isinstance(blk, dict) and blk.get('type') in ('tool_use', 'server_tool_use') and blk.get('id') not in seen_tool:
                        seen_tool.add(blk.get('id'))
                        tool_calls += 1
                        if blk.get('name') in ('WebSearch', 'web_search'):
                            web_searches += 1
                mid = m.get('id') or r.get('requestId') or r.get('uuid')
                if mid in seen_msg:
                    dup_lines += 1
                    if seen_msg[mid][1] != f:
                        cross_file.add(mid)
                    if seen_msg[mid][0] != run_id:
                        dup_cross += 1
                    continue
                seen_msg[mid] = (run_id, f)
                model = m.get('model') or 'unknown'
                u = m.get('usage') or {}
                if model == '<synthetic>':
                    synthetic += 1
                    if any(int(u.get(k) or 0) for k in ('input_tokens', 'output_tokens', 'cache_creation_input_tokens', 'cache_read_input_tokens')):
                        notes['synthetic_with_usage'] += 1
                    text = ' '.join(b.get('text', '') for b in (m.get('content') if isinstance(m.get('content'), list) else [])
                                    if isinstance(b, dict))
                    if LIMIT_RX.search(text):
                        limit_records += 1
                        limit_texts[text.strip()] += 1
                    continue
                ut = usage_tokens(u, notes)
                add_tokens(tok_by_model[model], ut)
                msg_log.append((t, model, ut))
        notes['duplicate_lines_same_message'] += dup_lines
        notes['duplicate_messages_across_runs'] += dup_cross
        return tok_by_model, first, last, synthetic, dict(tool_calls=tool_calls, web_search_calls=web_searches,
                                                          usage_limit_records=limit_records), cut

    for s in sessions:
        sid = s['sid']
        main_id = 'main' if single else f'main:{sid[:8]}'
        # ---- workflow agents (journal is the authority for label, stage and outcome)
        agent_wf = {}
        key_agents = collections.defaultdict(list)       # (workflow, journal key) -> agent ids in start order
        for wf, recs in s['journals'].items():
            for r in recs:
                if r.get('type') == 'started':
                    agent_wf[r['agentId']] = (wf, r)
                    if r.get('key'):
                        key_agents[(wf, r['key'])].append(r['agentId'])
        superseded_by, attempt = {}, {}
        for (wf, _k), ids in key_agents.items():
            for i, aid in enumerate(ids):
                attempt[aid] = i + 1
                if i + 1 < len(ids):
                    superseded_by[aid] = ids[i + 1]
        jterm = {}
        for wf, recs in s['journals'].items():
            for r in recs:
                if r.get('type') in ('result', 'failed') and r.get('agentId'):
                    jterm[r['agentId']] = r['type']
        records = []
        # main session first (its transcript holds the owner's messages and the harness cost-state)
        tok, first, last, syn, extra, _cut = scan([s['main']], main_id, owner=True)
        records.append(dict(run_id=main_id, session_id=sid, kind='main', parent=None, role='main session (orchestrator)',
                            journal_phase=None, deliverable='main-session', workflow=None, workflow_name=None, workflow_stage=None,
                            tok=tok, first=first, last=last, synthetic=syn, outcome='in_progress',
                            outcome_source='interactive session; no terminal record', files=[s['main']], extra=extra,
                            attempt=None, superseded_by=None))
        for aid in sorted(s['agent_files']):
            files = s['agent_files'][aid]
            meta = s['metas'].get(aid, {})
            tok, first, last, syn, extra, cut = scan(files, aid)
            if first is None:
                continue                                   # nothing of this agent existed at the cut-off
            if aid in agent_wf:
                wf, st = agent_wf[aid]
                wj = s['wf_json'].get(wf, {})
                name = wj.get('workflowName') or s['script_names'].get(wf)
                stage = (wj.get('args') or {}).get('stage') if isinstance(wj.get('args'), dict) else None
                # Journal records, the workflow JSON and meta.finished carry no timestamp, so they describe the
                # run as it is now. A transcript that continues after the cut-off means the run was still
                # going at the cut-off, whatever those records say today.
                if cut:
                    outcome, src = 'in_progress', 'transcript continues after the cut-off (running at the cut-off)'
                elif aid in jterm:
                    outcome, src = ('result' if jterm[aid] == 'result' else 'error'), f'journal {jterm[aid]} record'
                elif wj.get('status') == 'killed':
                    outcome, src = 'killed', 'agent started, no result record; workflow status killed'
                elif not wj:
                    outcome, src = 'in_progress', 'agent started, no result record; workflow record not written yet (running at roll-up)'
                else:
                    outcome, src = 'killed', f"agent started, no result record; workflow status {wj.get('status')}"
                dlv = deliverable_of(name, stage, st.get('phase'), st.get('label'))
                if dlv is None:
                    unmapped[name or f'(unnamed workflow {wf})'] += 1
                records.append(dict(run_id=aid, session_id=sid, kind='workflow-agent', parent=wf, role=st.get('label'),
                                    journal_phase=st.get('phase'), deliverable=dlv,
                                    workflow=wf, workflow_name=name, workflow_stage=stage, tok=tok, first=first, last=last,
                                    synthetic=syn, outcome=outcome, outcome_source=src, files=files, extra=extra,
                                    attempt=attempt.get(aid), superseded_by=superseded_by.get(aid)))
            else:
                desc = meta.get('description') or ''
                if cut:
                    outcome, src = 'in_progress', 'transcript continues after the cut-off (running at the cut-off)'
                elif meta.get('finished'):
                    outcome, src = 'result', 'meta.finished = true'
                else:
                    outcome, src = 'killed', 'meta.finished absent (ended without a final report)'
                dlv = deliverable_of(None, None, None, None, desc=desc)
                if dlv is None:
                    unmapped[f'(direct subagent) {desc}'] += 1
                records.append(dict(run_id=aid, session_id=sid, kind='direct-subagent', parent=main_id, role=desc or None,
                                    journal_phase=None, deliverable=dlv,
                                    workflow=None, workflow_name=None, workflow_stage=None, tok=tok, first=first,
                                    last=last, synthetic=syn, outcome=outcome, outcome_source=src, files=files, extra=extra,
                                    attempt=None, superseded_by=None))
        for rec in records:
            runs.append(finish_run(rec, pricer, projects))
        s['main_id'] = main_id
    if unmapped and not allow_unmapped:
        raise UnmappedWorkflow('workflow(s) with no deliverable in WF_DELIVERABLE: ' +
                               ', '.join(f'{k} ({v} runs)' for k, v in sorted(unmapped.items())))
    for r in runs:
        if r['deliverable'] is None:
            r['deliverable'] = 'unmapped'
    runs.sort(key=lambda r: (r['started_at'] or '', r['run_id']))
    notes['duplicate_messages_across_files'] = len(cross_file)
    totals = aggregate(runs, sessions, pricer, notes, owner_msgs, owner_cmds, cost_state, as_of,
                       files_scanned, lines_scanned, len(seen_msg), msg_log, cutoff, limit_texts, unmapped)
    return runs, totals


def outcome_detail(rec, called_model):
    """One short phrase saying why a run has its outcome (README: Outcome)."""
    extra = rec['extra']
    if rec['outcome'] == 'result':
        return 'finished with a result'
    if rec['outcome'] == 'in_progress':
        return 'still running at the cut-off' if rec['kind'] != 'main' else 'interactive session'
    limited = extra['usage_limit_records'] > 0
    if not called_model and limited:
        return 'refused by a usage limit before any model call (no tokens)'
    if limited:
        return 'interrupted by a usage limit'
    if rec['superseded_by']:
        return 'started, no result record; restarted under the same journal key (workflow resumed)'
    if not called_model:
        return 'launch ended before any model call (no tokens)'
    return 'started and used tokens, but wrote no result record' if rec['outcome'] == 'killed' else 'journal failed record'


def finish_run(rec, pricer, projects):
    tok = rec['tok']
    models = sorted(tok)
    tot = zero_tokens()
    for m in models:
        add_tokens(tot, tok[m])
    cost_by_model, unpriced = {}, []
    for m in models:
        c = pricer.cost(m, tok[m])
        if c is None:
            unpriced.append(m)
            cost_by_model[m] = 'unpriced'
        else:
            cost_by_model[m] = round(c, 6)
    # per-model pricing: the run keeps the cost of the models that are priced; the unpriced ones are named, never estimated
    cost = round(sum(v for v in cost_by_model.values() if not isinstance(v, str)), 6)
    first, last = rec['first'], rec['last']
    called = tot['messages'] > 0
    return {
        'run_id': rec['run_id'],
        'session_id': rec['session_id'],
        'kind': rec['kind'],
        'parent': rec['parent'] if rec['parent'] is not None else None,
        'role': rec['role'],
        'journal_phase': rec['journal_phase'],
        'deliverable': rec['deliverable'],
        'workflow_name': rec['workflow_name'],
        'workflow_stage': rec['workflow_stage'],
        'model_id': (models[0] if len(models) == 1 else ('mixed' if models else None)),
        'models': models,
        'called_model': called,
        'api_messages': tot['messages'],
        'synthetic_messages': rec['synthetic'],
        'usage_limit_records': rec['extra']['usage_limit_records'],
        'tool_calls': rec['extra']['tool_calls'],
        'web_search_calls': rec['extra']['web_search_calls'],
        'tokens_in': tot['in'],
        'tokens_out': tot['out'],
        'tokens_cache_write': tot['cw'],
        'tokens_cache_write_5m': tot['cw5m'],
        'tokens_cache_write_1h': tot['cw1h'],
        'tokens_cache_read': tot['cr'],
        'tokens_by_model': {m: {k: tok[m][k] for k in ('in', 'out', 'cw', 'cw5m', 'cw1h', 'cr', 'messages')} for m in models},
        'started_at': iso(first),
        'ended_at': iso(last),
        'wall_clock_s': round((last - first).total_seconds(), 1) if first and last else None,
        'attempt': rec['attempt'],
        'superseded_by': rec['superseded_by'],
        'outcome': rec['outcome'],
        'outcome_source': rec['outcome_source'],
        'outcome_detail': outcome_detail(rec, called),
        'cost_usd': cost,
        'cost_complete': not unpriced,
        'unpriced_models': unpriced,
        'cost_by_model_usd': cost_by_model,
        'cost_basis': pricer.basis(),
        'price_table': {'as_of': pricer.as_of, 'sha256': pricer.sha256, 'rows': sorted(m for m in models if m not in unpriced)},
        'human_minutes': None,
        'human_role': None,
        'source_files': [os.path.relpath(f, projects) for f in rec['files']],
    }


