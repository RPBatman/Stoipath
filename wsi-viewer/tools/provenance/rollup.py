#!/usr/bin/env python3
"""Provenance and cost roll-up of the agent work recorded in Claude Code transcripts.

Walks one Claude Code project directory (default /root/.claude/projects/-home-user-Stoipath):

  <session>.jsonl                                   main (interactive) session transcript
  <session>/subagents/agent-<id>.jsonl              subagents launched directly from the main session
  <session>/subagents/agent-<id>.meta.json          their description / finished flag
  <session>/subagents/workflows/<wf>/journal.jsonl  workflow journal: started (agentId, label, phase), result, failed
  <session>/subagents/workflows/<wf>/agent-*.jsonl  one transcript per workflow agent
  <session>/workflows/<wf>.json                     workflow record: name, args, status, startTime, durationMs
  <session>/workflows/scripts/<name>-<wf>.js        the workflow script (its file name gives the workflow name while
                                                    the workflow is still running and has no <wf>.json yet)

and writes

  docs/provenance/runs.jsonl    one line per agent run plus one per main session
  docs/provenance/totals.json   the aggregates the README block is rendered from

Definitions (also in docs/provenance/README.md):
  agent run      one subagent, launched by a workflow or directly from the main session, as recorded by a journal
                 `started` record or a subagent transcript. The interactive main session is counted separately and is
                 not an agent run. An agent run that "called a model" has at least one API response with usage.
  as-of cut-off  every transcript line later than --cutoff is ignored, so the figures are reproducible at a stated time.

Token counts come from message.usage on assistant records (input_tokens, output_tokens,
cache_creation_input_tokens with its 5m/1h split, cache_read_input_tokens). One API response is written as several
transcript lines (one per content block) carrying the same message.id and the same usage, and an agent transcript
can also exist in two files (an agent moved from a workflow to the background). Every message.id is therefore counted
once across all files. A workflow resumed after an interruption starts some agents a second time under the same
journal key: both attempts are kept as runs (their tokens were really used and no message id is shared) and the first
is marked `superseded_by` the second.

Cost is list price from prices.yaml, computed per model within a run. A model without a price is never estimated:
the run keeps the cost of its priced models, is flagged `cost_complete: false`, the totals carry `cost_complete: false`
and the command exits with status 2 and writes nothing (use --allow-unpriced to write an incomplete ledger with a
prominent warning). A workflow with no entry in WF_DELIVERABLE likewise stops the roll-up (status 3). The sum over
deliverables, over models and over runs must agree to the cent, or the roll-up stops (status 4).
Human review minutes are not in the transcripts: human_minutes is always null here.

Read-only on the transcripts; the only git commands are `git log` (first research-note date).

Usage:
  python3 wsi-viewer/tools/provenance/rollup.py                     # write runs.jsonl + totals.json
  python3 wsi-viewer/tools/provenance/rollup.py --readme            # also refresh the generated block in README.md
  python3 wsi-viewer/tools/provenance/rollup.py --cutoff 2026-11-10T20:30:00Z --readme
  python3 wsi-viewer/tools/provenance/rollup.py --projects DIR --out-dir DIR --prices FILE --as-of 2026-11-01
  python3 -I wsi-viewer/tools/provenance/test_rollup.py             # the tool's own tests
"""
