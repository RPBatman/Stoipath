def fm(n):
    return f'{n:,}'


def fmm(n):
    return f'{n / 1e6:,.2f}'


def render(t):
    L = []
    L.append(f"Roll-up as of **{t['as_of']}** (generated {t['generated_at']}). Inputs: {fm(t['inputs']['transcript_files'])} transcript "
             f"files, {fm(t['inputs']['transcript_lines'])} lines, {fm(t['inputs']['unique_assistant_messages'])} unique API responses "
             f"(message ids; {fm(t['inputs']['duplicate_lines_same_message'])} repeated lines of the same response skipped, among them "
             f"{fm(t['inputs']['duplicate_messages_across_files'])} responses recorded in two files; "
             f"{fm(t['inputs']['duplicate_messages_across_runs'])} shared between runs), {t['inputs']['workflows']} workflow runs.")
    L.append('')
    r = t['runs']
    k = r['by_kind']
    L.append(f"**Runs: {fm(r['total'])}** = {k.get('workflow-agent', 0)} workflow agents + {k.get('direct-subagent', 0)} direct "
             f"subagents + {k.get('main', 0)} main session. Outcomes: " +
             ', '.join(f'{v} {o}' for o, v in sorted(r['outcomes'].items(), key=lambda kv: -kv[1])) + '.')
    L.append('')
    L.append('| Model | API responses | Input (uncached) | Output | Cache write | Cache read | List-price cost (USD) |')
    L.append('|---|---:|---:|---:|---:|---:|---:|')
    for m, v in t['by_model'].items():
        c = v['cost_usd']
        L.append(f"| `{m}` | {fm(v['messages'])} | {fm(v['in'])} | {fm(v['out'])} | {fm(v['cw'])} | {fm(v['cr'])} | "
                 f"{('%s' % c) if isinstance(c, str) else '{:,.2f}'.format(c)} |")
    tk = t['tokens']
    L.append(f"| **All** | {fm(t['inputs']['unique_assistant_messages'])} | {fm(tk['in'])} | {fm(tk['out'])} | {fm(tk['cache_write'])} | "
             f"{fm(tk['cache_read'])} | **{t['cost_usd_total']:,.2f}** |")
    L.append('')
    L.append(f"Tokens in + out = **{fmm(tk['in_plus_out'])} M** (the abstract's `[T]` rule); cache write {fmm(tk['cache_write'])} M and "
             f"cache read {fmm(tk['cache_read'])} M stated separately; all four kinds together {fmm(tk['all_kinds'])} M."
             + (f" Unpriced models: {', '.join(t['unpriced_models'])}." if t['unpriced_models'] else ' Every model in the ledger is priced.'))
    L.append('')
    L.append('| Phase | Runs | Workflows | Outcomes | In + out (M) | Cache write (M) | Cache read (M) | Cost (USD) | First start | Last end | Agent wall-clock (h) |')
    L.append('|---|---:|---:|---|---:|---:|---:|---:|---|---|---:|')
    for p, v in t['phases'].items():
        oc = ', '.join(f'{n} {o}' for o, n in sorted(v['outcomes'].items(), key=lambda kv: -kv[1]))
        L.append(f"| {p} | {v['runs']} | {v['workflow_count']} | {oc} | {fmm(v['tokens_in'] + v['tokens_out'])} | {fmm(v['tokens_cache_write'])} | "
                 f"{fmm(v['tokens_cache_read'])} | {v['cost_usd']:,.2f}{' + unpriced' if v['has_unpriced'] else ''} | {v['first_start']} | "
                 f"{v['last_end']} | {('%.1f (span, mostly idle)' % v['agent_wall_clock_h']) if p == 'main-session' else '%.1f' % v['agent_wall_clock_h']} |")
    L.append('')
    w = t['wall_clock']
    L.append(f"**Wall-clock:** first transcript line {w['first']}, last {w['last']} — span {w['span_h']} h ({w['span_days']} days). "
             f"At least one subagent was running for {w['agent_active_union_h']} h (union of run intervals); the subagents' own "
             f"wall-clock adds up to {w['agent_wall_clock_sum_h']} agent-hours. Subagent activity fell on {len(w['agent_active_dates'])} "
             f"calendar dates: {', '.join(w['agent_active_dates'])}.")
    L.append('')
    d = t['days']
    if d:
        L.append(f"**Days (`[D]`):** first research-note commit {d['first_research_note_commit']} (`git log` of `wsi-viewer/docs/research`) "
                 f"→ {d['to_date']}: **{d['elapsed_days']} days elapsed** ({d['calendar_days_inclusive']} calendar days counted inclusively).")
        L.append('')
    o = t['owner_messages']
    L.append(f"**Owner's own messages (aid for `[H]`, not a measure of it):** {o['count']} typed messages in the main session "
             f"(plus {o['slash_commands']['count']} slash commands), per day: " +
             ', '.join(f'{day} {n}' for day, n in o['per_day'].items()) + '. Timestamps (UTC):')
    L.append('')
    by_day = collections.defaultdict(list)
    for x in o['timestamps']:
        by_day[x[:10]].append(x[11:19])
    for day, xs in by_day.items():
        L.append(f"- {day}: {', '.join(xs)}")
    if o['slash_commands']['timestamps']:
        L.append(f"- slash commands: {', '.join(x[:19].replace('T', ' ') for x in o['slash_commands']['timestamps'])}")
    L.append('')
    h = t['harness_cost_state']
    if h:
        L.append(f"**Cross-check — Claude Code's own cost-state record** (last one in the main transcript, written after "
                 f"{h['record_written_after']}): US${h['total_cost_usd']:,.2f} in total. " + h['note'] + '.')
        L.append('')
        L.append('| Model | Harness cost (USD) | Harness output | Harness cache read | Ledger, same cut-off (USD) | Ledger output | Ledger cache read |')
        L.append('|---|---:|---:|---:|---:|---:|---:|')
        for m in sorted(set(h['models']) | set(h['ledger_same_cutoff'])):
            hv = h['models'].get(m, {})
            lv = h['ledger_same_cutoff'].get(m, {})
            hc = hv.get('cost_usd')
            lc = lv.get('cost_usd')
            L.append(f"| `{m}` | {'%s' % ('{:,.2f}'.format(hc) if isinstance(hc, (int, float)) else '—')} | {fm(hv['output']) if hv.get('output') is not None else '—'} | "
                     f"{fm(hv['cache_read']) if hv.get('cache_read') is not None else '—'} | "
                     f"{('{:,.2f}'.format(lc) if isinstance(lc, (int, float)) else (lc or '— (no transcript messages)'))} | "
                     f"{fm(lv['output']) if lv else '—'} | {fm(lv['cache_read']) if lv else '—'} |")
    return '\n'.join(L)


def update_readme(path, block):
    text = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        text = pre + BEGIN + '\n' + block + '\n' + END + post
    else:
        text = text.rstrip() + '\n\n' + BEGIN + '\n' + block + '\n' + END + '\n'
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--projects', default=DEFAULT_PROJECTS, help='Claude Code project directory (default %(default)s)')
    ap.add_argument('--out-dir', default=DEFAULT_OUT, help='where runs.jsonl / totals.json go (default %(default)s)')
    ap.add_argument('--prices', default=None, help='prices.yaml (default <out-dir>/prices.yaml)')
    ap.add_argument('--as-of', default=dt.date.today().isoformat(), help='roll-up date for the days count (default today)')
    ap.add_argument('--readme', action='store_true', help='refresh the generated block in <out-dir>/README.md')
    ap.add_argument('--print', action='store_true', help='print the Markdown block to stdout')
    a = ap.parse_args(argv)
    prices_path = a.prices or os.path.join(a.out_dir, 'prices.yaml')
    pricer = Pricer(load_yaml(prices_path))
    runs, totals = rollup(a.projects, pricer, a.as_of)
    os.makedirs(a.out_dir, exist_ok=True)
    with open(os.path.join(a.out_dir, 'runs.jsonl'), 'w', encoding='utf-8') as fh:
        for r in runs:
            fh.write(json.dumps(r, sort_keys=False) + '\n')
    with open(os.path.join(a.out_dir, 'totals.json'), 'w', encoding='utf-8') as fh:
        json.dump(totals, fh, indent=1)
        fh.write('\n')
    block = render(totals)
    if a.readme:
        update_readme(os.path.join(a.out_dir, 'README.md'), block)
    if a.print:
        print(block)
    print(f"runs={totals['runs']['total']} tokens_in+out={totals['tokens']['in_plus_out']} cost_usd={totals['cost_usd_total']} "
          f"unpriced={totals['unpriced_models']} -> {a.out_dir}", file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
