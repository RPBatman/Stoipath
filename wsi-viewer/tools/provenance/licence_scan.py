#!/usr/bin/env python3
"""Licence and secret scan for the Stage-0 client, the OpenSeadragon comparator and the Python tools (evidence E7).

Read-only. Inputs:
  stage0/client/package.json + package-lock.json       npm dependency graph (dev / optional / runtime)
  the published measurement build (git show <deploy-ref>:client/dist/...) and the local stage0/client/dist, read as files
  stage0/comparator/vendor/*                            vendored third-party files (OpenSeadragon)
  every tracked *.py (git ls-files)                     third-party imports; versions/licences from installed metadata
  every tracked text file (git ls-files)                credential patterns (values are never printed or stored)

Writes docs/provenance/licence-scan.json and, with --md, refreshes the generated block in docs/provenance/licences.md.
The SBOM (docs/provenance/sbom.cdx.json) is produced separately by @cyclonedx/cyclonedx-npm; see licences.md.

Usage:
  python3 wsi-viewer/tools/provenance/licence_scan.py [--md] [--deploy-ref stage0-deploy] [--site-packages DIR ...]
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WSI = os.path.normpath(os.path.join(HERE, '..', '..'))
REPO = os.path.normpath(os.path.join(WSI, '..'))
CLIENT = os.path.join(WSI, 'stage0', 'client')
COMPARATOR = os.path.join(WSI, 'stage0', 'comparator')
OUT = os.path.join(WSI, 'docs', 'provenance')
BEGIN = '<!-- licence-scan:begin (generated by tools/provenance/licence_scan.py --md; do not edit by hand) -->'
END = '<!-- licence-scan:end -->'

# E7 allow-list (evidence-table.md): Apache-2.0, MIT, BSD-2/3, ISC, Zlib, Unicode; MPL-2.0 for tooling only.
PERMISSIVE = {'Apache-2.0', 'MIT', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', 'Unicode-DFS-2016', 'Unicode-3.0',
              '0BSD', 'CC0-1.0', 'MIT-CMU', 'BlueOak-1.0.0', 'Python-2.0', 'PSF-2.0'}
E7_ALLOW = {'Apache-2.0', 'MIT', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', 'Unicode-DFS-2016', 'Unicode-3.0'}
COPYLEFT = re.compile(r'\b(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|OSL|CC-BY-SA|SSPL|CPAL)', re.I)

SECRET_PATTERNS = {
    'AWS access key id': r'(A3T[A-Z0-9]|AKIA|ASIA|ABIA|ACCA)[A-Z0-9]{16}',
    'AWS secret key assignment': r'(?i)aws_?secret_?access_?key\s*[:=]\s*\S+',
    'GitHub token': r'\b(gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{22,})',
    'Private key block': r'-----BEGIN ([A-Z]+ )?PRIVATE KEY( BLOCK)?-----',
    'Bearer token': r'(?i)\bbearer\s+[A-Za-z0-9\-._~+/]{20,}=*',
    'Anthropic API key': r'sk-ant-[A-Za-z0-9_\-]{20,}',
    'OpenAI-style key': r'\bsk-[A-Za-z0-9]{32,}',
    'Slack token': r'xox[abprs]-[A-Za-z0-9-]{10,}',
    'Google API key': r'AIza[0-9A-Za-z\-_]{35}',
    'JSON Web Token': r'eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}',
    'Stripe live key': r'(sk|rk)_live_[A-Za-z0-9]{20,}',
    'Generic secret assignment': r'(?i)\b(api[_-]?key|secret[_-]?key|access[_-]?token|auth[_-]?token|client[_-]?secret|password)\b\s*[:=]\s*["\']?[A-Za-z0-9/+_\-]{16,}',
}
SECRET_FILES = re.compile(r'(^|/)(\.env(\..*)?|.*\.pem|.*\.key|id_rsa.*|id_ed25519.*|.*\.p12|.*\.pfx|\.npmrc|\.netrc|\.pypirc|credentials(\.json)?)$')
THIRD_PARTY_MARKERS = re.compile(r'@license|Copyright \(C\)|Copyright \d{4}|SPDX-License-Identifier|\(c\) \d{4}', re.I)


def git(*args, binary=False):
    r = subprocess.run(['git', '-C', REPO, *args], capture_output=True, check=False)
    return r.stdout if binary else r.stdout.decode('utf-8', 'replace')


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def classify(lic):
    lic = lic or 'UNKNOWN'
    ids = [x for x in re.split(r'\s+(?:AND|OR|WITH)\s+|[()]', lic) if x.strip()]
    copyleft = bool(COPYLEFT.search(lic))
    in_allow = all(i.strip() in E7_ALLOW for i in ids) and ids != []
    permissive = all(i.strip() in PERMISSIVE for i in ids) and ids != []
    return copyleft, in_allow, permissive


# ------------------------------------------------------------------------------------------------ npm
def npm_scan():
    pkg = json.load(open(os.path.join(CLIENT, 'package.json')))
    lock = json.load(open(os.path.join(CLIENT, 'package-lock.json')))
    rows = []
    for path, v in lock.get('packages', {}).items():
        if not path:
            continue
        name = path.split('node_modules/')[-1]
        installed = os.path.exists(os.path.join(CLIENT, path, 'package.json'))
        lic = v.get('license') or 'UNKNOWN'
        cl, allow, perm = classify(lic)
        kind = 'dev' if v.get('dev') else ('runtime' if not v.get('devOptional') else 'dev-optional')
        rows.append({'name': name, 'version': v.get('version'), 'licence': lic, 'scope': kind,
                     'optional': bool(v.get('optional')), 'platform': '/'.join(filter(None, [','.join(v.get('os') or []), ','.join(v.get('cpu') or [])])) or None,
                     'installed_here': installed, 'direct': name in (pkg.get('devDependencies') or {}) or name in (pkg.get('dependencies') or {}),
                     'copyleft': cl, 'e7_allow_list': allow})
    rows.sort(key=lambda r: (r['optional'], not r['direct'], r['name']))
    return {'package': pkg.get('name'), 'dependencies': pkg.get('dependencies') or {}, 'devDependencies': pkg.get('devDependencies') or {},
            'lockfileVersion': lock.get('lockfileVersion'), 'lock_sha256': sha256(open(os.path.join(CLIENT, 'package-lock.json'), 'rb').read()),
            'packages': rows}


# ------------------------------------------------------------------------------------------------ bundles
def bundle_scan(deploy_ref):
    out = {}
    names = [n for n in git('ls-tree', '-r', '--name-only', deploy_ref).splitlines() if n.startswith('client/dist/')]
    pub = []
    for n in names:
        b = git('show', f'{deploy_ref}:{n}', binary=True)
        pub.append({'path': n, 'bytes': len(b), 'sha256': sha256(b),
                    'third_party_markers': len(THIRD_PARTY_MARKERS.findall(b.decode('utf-8', 'replace')))})
    out['published'] = {'ref': deploy_ref, 'commit': git('log', '-1', '--format=%h %aI', deploy_ref, '--', 'client/dist').strip(), 'files': pub}
    loc = []
    dist = os.path.join(CLIENT, 'dist')
    for root, _, files in os.walk(dist):
        for f in sorted(files):
            p = os.path.join(root, f)
            b = open(p, 'rb').read()
            loc.append({'path': os.path.relpath(p, WSI), 'bytes': len(b), 'sha256': sha256(b),
                        'third_party_markers': len(THIRD_PARTY_MARKERS.findall(b.decode('utf-8', 'replace')))})
    out['local_dist'] = {'note': 'working-tree build, not tracked; read as found (not rebuilt)', 'files': loc}
    return out


# ------------------------------------------------------------------------------------------------ comparator
def comparator_scan():
    vend = os.path.join(COMPARATOR, 'vendor')
    rows = []
    if not os.path.isdir(vend):
        return rows
    for lib in sorted(os.listdir(vend)):
        d = os.path.join(vend, lib)
        files = sorted(os.listdir(d)) if os.path.isdir(d) else []
        version, lic_text = None, None
        for f in files:
            b = open(os.path.join(d, f), 'rb').read()
            m = re.search(rb'//!\s*' + re.escape(lib.encode()) + rb'\s+([0-9][0-9.]*)', b[:400], re.I)
            if m:
                version = m.group(1).decode()
            if f.upper().startswith('LICENSE'):
                lic_text = b.decode('utf-8', 'replace')
        lic = 'UNKNOWN'
        if lic_text and 'Redistribution and use in source and binary forms' in lic_text:
            lic = 'BSD-3-Clause' if 'Neither the name' in lic_text else 'BSD-2-Clause'
        elif lic_text and 'Permission is hereby granted, free of charge' in lic_text:
            lic = 'MIT'
        cl, allow, _ = classify(lic)
        rows.append({'name': lib, 'version': version, 'licence': lic, 'scope': 'runtime (comparator page only)',
                     'files': [{'file': f, 'sha256': sha256(open(os.path.join(d, f), 'rb').read())} for f in files],
                     'licence_file_present': lic_text is not None, 'copyleft': cl, 'e7_allow_list': allow})
    return rows


# ------------------------------------------------------------------------------------------------ python
def python_scan(site_dirs):
    import importlib.metadata as md
    tracked = [f for f in (git('ls-files').splitlines() + git('ls-files', '--others', '--exclude-standard').splitlines()) if f.endswith('.py')]
    local = {os.path.splitext(os.path.basename(f))[0] for f in tracked}
    stdlib = set(getattr(sys, 'stdlib_module_names', ()))
    imports = {}
    for f in tracked:
        try:
            tree = ast.parse(open(os.path.join(REPO, f), encoding='utf-8').read())
        except Exception:
            continue
        for node in ast.walk(tree):
            mods = []
            if isinstance(node, ast.Import):
                mods = [a.name.split('.')[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                mods = [node.module.split('.')[0]]
            for m in mods:
                if m in stdlib or m in local or m == '__future__':
                    continue
                imports.setdefault(m, set()).add(f)
    dist_of = {'PIL': 'pillow', 'yaml': 'PyYAML'}
    paths = list(site_dirs) + [None]
    rows = []
    for mod, files in sorted(imports.items()):
        dname = dist_of.get(mod, mod)
        version = lic = where = None
        for p in paths:
            try:
                dists = md.distributions(path=[p]) if p else md.distributions()
                for d in dists:
                    if (d.metadata.get('Name') or '').lower() == dname.lower():
                        version = d.version
                        lic = d.metadata.get('License-Expression') or d.metadata.get('License') or None
                        if not lic:
                            cls = [c.split('::')[-1].strip() for c in (d.metadata.get_all('Classifier') or []) if c.startswith('License')]
                            lic = '; '.join(cls) or None
                        where = p or 'system site-packages'
                        raise StopIteration
            except StopIteration:
                break
        cl, allow, perm = classify(lic or 'UNKNOWN')
        groups = sorted({('stage0 tools' if '/stage0/tools/' in f else 'stage0 harness' if '/harness/' in f else
                          'verification artefacts' if '/verification/' in f else 'design checks' if '/design/' in f else
                          'planning pipeline' if '/planning-pipeline/' in f else
                          'provenance tools (optional import)' if '/tools/provenance/' in f else 'other') for f in files})
        rows.append({'module': mod, 'distribution': dname, 'version': version, 'licence': lic or 'UNKNOWN (not installed here)',
                     'metadata_from': where, 'used_by': groups, 'files': sorted(files), 'scope': 'tooling (never shipped to a browser)',
                     'copyleft': cl, 'e7_allow_list': allow, 'permissive': perm})
    return rows


# ------------------------------------------------------------------------------------------------ harness externals
def harness_externals():
    """Packages the headless harness loads from outside package.json (browser.mjs resolves playwright from the global root)."""
    rows = []
    harness = os.path.join(CLIENT, 'harness')
    wanted = set()
    for f in sorted(os.listdir(harness)) if os.path.isdir(harness) else []:
        if f.endswith(('.mjs', '.js')):
            t = open(os.path.join(harness, f), encoding='utf-8').read()
            wanted |= set(re.findall(r"require\(\s*['\"]([a-z@][\w@/.-]*)['\"]", t))
            wanted |= {m for m in re.findall(r"from\s+['\"]([a-z@][\w@/.-]*)['\"]", t) if not m.startswith('node:')}
    try:
        groot = subprocess.run(['npm', 'root', '-g'], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        groot = None
    for name in sorted(wanted):
        pj = os.path.join(groot, name, 'package.json') if groot else None
        v = lic = None
        deps = {}
        if pj and os.path.exists(pj):
            d = json.load(open(pj))
            v, lic, deps = d.get('version'), d.get('license'), d.get('dependencies') or {}
        cl, allow, _ = classify(lic or 'UNKNOWN')
        rows.append({'name': name, 'version': v, 'licence': lic or 'UNKNOWN (not found in global npm root)', 'dependencies': deps,
                     'scope': 'harness only (global install, not in package.json, never shipped)', 'copyleft': cl, 'e7_allow_list': allow})
    return rows


# ------------------------------------------------------------------------------------------------ secrets
def secret_scan(include_untracked=True):
    tracked = [f for f in git('ls-files', '-z').split('\0') if f]
    untracked = [f for f in git('ls-files', '--others', '--exclude-standard', '-z').split('\0') if f] if include_untracked else []
    files = tracked + untracked
    hits, name_hits = [], []
    scanned = binary = 0
    for f in files:
        if SECRET_FILES.search(f):
            name_hits.append(f)
        p = os.path.join(REPO, f)
        try:
            b = open(p, 'rb').read()
        except OSError:
            continue
        if b'\0' in b[:8192]:
            binary += 1
            continue
        scanned += 1
        t = b.decode('utf-8', 'replace')
        for label, pat in SECRET_PATTERNS.items():
            for m in re.finditer(pat, t):
                hits.append({'file': f, 'line': t.count('\n', 0, m.start()) + 1, 'pattern': label, 'match_length': len(m.group(0))})
    return {'tracked_files': len(tracked), 'untracked_not_ignored_files': len(untracked), 'text_files_scanned': scanned, 'binary_files_skipped': binary,
            'patterns': list(SECRET_PATTERNS), 'findings': hits, 'sensitive_file_names': name_hits,
            'note': 'values are never printed or stored; only file, line, pattern name and match length'}


# ------------------------------------------------------------------------------------------------ report
def md_block(r):
    L = []
    npm = r['npm']
    pk = npm['packages']
    n_dev = sum(1 for p in pk if p['scope'].startswith('dev'))
    n_run = sum(1 for p in pk if p['scope'] == 'runtime')
    n_opt = sum(1 for p in pk if p['optional'])
    n_inst = sum(1 for p in pk if p['installed_here'])
    non_allow = [p for p in pk if not p['e7_allow_list']]
    L.append(f"Scan run {r['generated_at']}. **Client (`stage0/client`, lockfile v{npm['lockfileVersion']}, sha256 `{npm['lock_sha256'][:16]}…`):** "
             f"{len(pk)} packages in `package-lock.json` — {n_dev} dev, {n_run} runtime; {n_opt} of them are optional platform binaries "
             f"(only {n_inst} packages are installed on this linux-x64 machine). `dependencies`: {json.dumps(npm['dependencies'])}; "
             f"`devDependencies`: {json.dumps(npm['devDependencies'])}. Outside the E7 allow-list: **{len(non_allow)}**; copyleft: "
             f"**{sum(1 for p in pk if p['copyleft'])}**.")
    L.append('')
    L.append('| Package | Version | Licence | Dev / runtime | Optional (platform) | Direct | Copyleft | E7 allow-list |')
    L.append('|---|---|---|---|---|---|---|---|')
    for p in pk:
        L.append(f"| `{p['name']}` | {p['version']} | {p['licence']} | {p['scope']} | {('yes (' + (p['platform'] or '') + ')') if p['optional'] else 'no'} | "
                 f"{'yes' if p['direct'] else ''} | {'**yes**' if p['copyleft'] else 'no'} | {'yes' if p['e7_allow_list'] else '**no**'} |")
    L.append('')
    b = r['bundles']
    L.append(f"**Shipped client code.** Published measurement build `{b['published']['ref']}` (last `client/dist` commit {b['published']['commit']}):")
    L.append('')
    L.append('| File | Bytes | SHA-256 | Third-party licence/copyright markers |')
    L.append('|---|---:|---|---:|')
    for f in b['published']['files']:
        L.append(f"| `{f['path']}` | {f['bytes']:,} | `{f['sha256'][:16]}…` | {f['third_party_markers']} |")
    L.append('')
    L.append(f"Local working-tree `stage0/client/dist` ({len(b['local_dist']['files'])} files, read as found, not rebuilt; it is being "
             f"rebuilt by the shell workflow and is not the measurement build): third-party markers in "
             f"{sum(1 for f in b['local_dist']['files'] if f['third_party_markers'])} files.")
    L.append('')
    if r['comparator']:
        L.append('**Comparator page (`stage0/comparator`), vendored files:**')
        L.append('')
        L.append('| Library | Version | Licence | Scope | Licence file | Files (SHA-256) | Copyleft | E7 allow-list |')
        L.append('|---|---|---|---|---|---|---|---|')
        for c in r['comparator']:
            fl = '; '.join(f"`{x['file']}` `{x['sha256'][:16]}…`" for x in c['files'])
            L.append(f"| {c['name']} | {c['version']} | {c['licence']} | {c['scope']} | {'yes' if c['licence_file_present'] else '**no**'} | {fl} | "
                     f"{'**yes**' if c['copyleft'] else 'no'} | {'yes' if c['e7_allow_list'] else '**no**'} |")
        L.append('')
    else:
        L.append('**Comparator page:** no `stage0/comparator/vendor` directory at scan time.')
        L.append('')
    if r.get('harness'):
        L.append('**Headless harness — packages loaded from outside `package.json`:** ' + '; '.join(
            f"`{h['name']}` {h['version']} ({h['licence']}; deps {json.dumps(h['dependencies'])}; {h['scope']})" for h in r['harness']) + '.')
        L.append('')
    L.append('**Python tools — third-party imports (tooling only, never shipped to a browser):**')
    L.append('')
    L.append('| Module | Distribution | Version (metadata) | Licence | Used by | Copyleft | Permissive |')
    L.append('|---|---|---|---|---|---|---|')
    for p in r['python']:
        L.append(f"| `{p['module']}` | {p['distribution']} | {p['version'] or '—'} | {p['licence']} | {', '.join(p['used_by'])} | "
                 f"{'**yes**' if p['copyleft'] else 'no'} | {'yes' if p['permissive'] else 'check'} |")
    L.append('')
    s = r['secrets']
    L.append(f"**Secret scan:** {s['tracked_files']} tracked files (`git ls-files`) plus {s['untracked_not_ignored_files']} untracked, "
             f"not-ignored files about to be committed (`git ls-files --others --exclude-standard`); {s['text_files_scanned']} text files scanned, "
             f"{s['binary_files_skipped']} binary files skipped; {len(SECRET_PATTERNS)} patterns. Findings: **{len(s['findings'])}**"
             + (':' if s['findings'] else '.') )
    L.append('')
    if s['findings']:
        L.append('| File | Line | Pattern | Match length |')
        L.append('|---|---:|---|---:|')
        for h in s['findings']:
            L.append(f"| `{h['file']}` | {h['line']} | {h['pattern']} | {h['match_length']} |")
        L.append('')
    L.append(f"Sensitive file names tracked: {', '.join('`' + x + '`' for x in s['sensitive_file_names']) or 'none'}; `.env` files tracked: "
             f"{sum(1 for x in s['sensitive_file_names'] if re.search(r'(^|/)\\.env', x))}.")
    return '\n'.join(L)


def main(argv=None):
    import datetime as dt
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--deploy-ref', default='stage0-deploy')
    ap.add_argument('--site-packages', action='append', default=[], help='extra site-packages dir for Python licence metadata')
    ap.add_argument('--md', action='store_true', help='refresh the generated block in <out-dir>/licences.md')
    ap.add_argument('--out-dir', default=OUT, help='where licence-scan.json (and licences.md) live (default %(default)s)')
    a = ap.parse_args(argv)
    out = a.out_dir
    r = {'generated_at': dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
         'npm': npm_scan(), 'bundles': bundle_scan(a.deploy_ref), 'comparator': comparator_scan(),
         'harness': harness_externals(), 'python': python_scan(a.site_packages), 'secrets': secret_scan()}
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'licence-scan.json'), 'w', encoding='utf-8') as fh:
        json.dump(r, fh, indent=1)
        fh.write('\n')
    block = md_block(r)
    if a.md:
        p = os.path.join(out, 'licences.md')
        text = open(p, encoding='utf-8').read() if os.path.exists(p) else ''
        if BEGIN in text and END in text:
            pre, rest = text.split(BEGIN, 1)
            _, post = rest.split(END, 1)
            text = pre + BEGIN + '\n' + block + '\n' + END + post
        else:
            text = text.rstrip() + '\n\n' + BEGIN + '\n' + block + '\n' + END + '\n'
        open(p, 'w', encoding='utf-8').write(text)
    else:
        print(block)
    npm_non = sum(1 for p in r['npm']['packages'] if not p['e7_allow_list'])
    print(f"npm packages={len(r['npm']['packages'])} outside allow-list={npm_non} comparator={len(r['comparator'])} "
          f"python third-party={len(r['python'])} secret findings={len(r['secrets']['findings'])}", file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
