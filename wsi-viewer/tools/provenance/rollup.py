#!/usr/bin/env python3
"""Provenance and cost roll-up of the agent work recorded in Claude Code transcripts.

Walks one Claude Code project directory (default /root/.claude/projects/-home-user-Stoipath):

  <session>.jsonl                                   main (interactive) session transcript
  <session>/subagents/agent-<id>.jsonl              subagents launched directly from the main session
  <session>/subagents/agent-<id>.meta.json          their description / finished flag
  <session>/subagents/workflows/<wf>/journal.jsonl  workflow journal: started (agentId, label, phase), result, failed
  <session>/subagents/workflows/<wf>/agent-*.jsonl  one transcript per workflow agent
  <session>/workflows/<wf>.json                     workflow record: name, args, status, startTime, durationMs

and writes

  docs/provenance/runs.jsonl    one line per agent run plus one per main session
  docs/provenance/totals.json   the aggregates the README block is rendered from

Token counts come from message.usage on assistant records (input_tokens, output_tokens,
cache_creation_input_tokens with its 5m/1h split, cache_read_input_tokens). One API response is written as several
transcript lines (one per content block) carrying the same message.id and the same usage, and an agent transcript
can also exist in two files (an agent moved from a workflow to the background). Every message.id is therefore counted
once across all files. Cost is list price from prices.yaml; a model without a price is reported as "unpriced", never
estimated. Human review minutes are not in the transcripts: human_minutes is always null here.

Read-only on the transcripts; the only git commands are `git log` (first research-note date).

Usage:
  python3 wsi-viewer/tools/provenance/rollup.py                     # write runs.jsonl + totals.json
  python3 wsi-viewer/tools/provenance/rollup.py --readme            # also refresh the generated block in README.md
  python3 wsi-viewer/tools/provenance/rollup.py --projects DIR --out-dir DIR --prices FILE --as-of 2026-11-01
"""
